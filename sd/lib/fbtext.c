#define FONT_COUNT (sizeof(font)/sizeof(font[0]))



uint8_t *get_char(char c)
{
    int i;

    c=toupper((unsigned char)c);

    for(i=0;i<FONT_COUNT;i++)
        if(font[i].c==c)
            return font[i].d;

    return font[FONT_COUNT-1].d;
}



void fill(uint16_t color)
{
    int i;

    for(i=0;i<WIDTH*HEIGHT;i++)
        fb[i]=color;
}



void pixel(int x,int y,uint16_t c)
{
    if(x>=0 && y>=0 && x<WIDTH && y<HEIGHT)
        fb[y*WIDTH+x]=c;
}



void draw_char(int x, int y, char c)
{
    uint8_t *p = get_char(c);

    for (int r = 0; r < 8; r++)
    {
        for (int col = 0; col < 8; col++)
        {
            if (p[r] & (1 << (7 - col)))
                pixel(x + col, y + r, WHITE);
        }
    }
}


void draw_text_wrap(char *s)
{
    int max_chars = WIDTH / CHAR_W;

    char lines[40][64];
    int line_count = 0;

    int pos = 0;
    int len = strlen(s);


    while(pos < len && line_count < 40)
    {
        int count = 0;
        int last_space = -1;


        while(pos + count < len && count < max_chars)
        {
            if(s[pos+count]==' ')
                last_space=count;

            count++;
        }


        if(pos+count < len && last_space > 0)
            count = last_space;


        memcpy(lines[line_count], &s[pos], count);
        lines[line_count][count]=0;

        line_count++;


        pos += count;


        while(s[pos]==' ')
            pos++;
    }



    int y = (HEIGHT - line_count*CHAR_H)/2;


    for(int l=0;l<line_count;l++)
    {
        int len2=strlen(lines[l]);

        int x=(WIDTH-len2*CHAR_W)/2;


        for(int i=0;i<len2;i++)
        {
            draw_char(
                x+i*CHAR_W,
                y,
                lines[l][i]
            );
        }

        y+=CHAR_H;
    }
}


int main(int argc,char **argv)
{
    int fd;

    uint16_t bg=BLACK;


    if(argc<2)
    {
        printf("usage: %s TEXT [RGB]\n",argv[0]);
        return 1;
    }


    if(argc>=3)
    {
        unsigned int rgb;

        sscanf(argv[2],"%x",&rgb);

        bg=ARGB4444(
            0xf,
            (rgb>>16)&0xf,
            (rgb>>8)&0xf,
            rgb&0xf
        );
    }


    fill(bg);


    draw_text_wrap(argv[1]);



    fd=open("/dev/fb0",O_WRONLY);

    if(fd<0)
    {
        perror("fb0");
        return 1;
    }

    for(int i=0;i<4;i++)
        write(fd,fb,FB_SIZE);


    close(fd);

    return 0;
}
